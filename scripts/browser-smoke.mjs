async function request(route, method = "GET", body) {
  const response = await fetch(origin + "/api" + route, {
    method,
    headers: {
      "Content-Type": "application/json",
      "X-Lighthouse-Client": "workspace",
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  const json = await response.json();
  assert.ok(response.ok, JSON.stringify(json));
  return json;
}
async function audit(body) {
  await request("/audit/run", "POST", body);
  const deadline = Date.now() + 240000;
  while (Date.now() < deadline) {
    const status = await request("/audit/status");
    if (!status.inProgress) return status;
    await new Promise((resolve) => setTimeout(resolve, 1000));
  }
  throw new Error("Real audit exceeded four minutes");
}
